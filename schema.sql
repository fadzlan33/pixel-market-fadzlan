create table if not exists public.ads (
 id bigint generated by default as identity primary key,
 brand text not null check (char_length(brand) between 1 and 60),
 url text not null check (url like 'https://%' or url like 'http://%'),
 x integer not null check (x between 0 and 990 and x % 10 = 0),
 y integer not null check (y between 0 and 990 and y % 10 = 0),
 w integer not null check (w between 10 and 1000 and w % 10 = 0),
 h integer not null check (h between 10 and 1000 and h % 10 = 0),
 logo_data text not null,
 status text not null default 'pending' check (status in ('pending','approved','rejected')),
 created_at timestamptz not null default now()
);
alter table public.ads enable row level security;
create policy "Public read approved ads" on public.ads for select to anon, authenticated using (status='approved');
create policy "Public submit pending ads" on public.ads for insert to anon, authenticated with check (status='pending');
